def _build_trading_calendar() -> Tuple[List[str], Dict[str, int], Dict[str, str]]:
    days_list = []
    days_index = {}
    nearest_trading_day = {}
    start = datetime(2020, 1, 1)
    end = datetime(2027, 12, 31)
    curr = start
    last_trading = start.strftime("%Y-%m-%d")

    while curr <= end:
        ds = curr.strftime("%Y-%m-%d")
        is_weekend = curr.weekday() >= 5
        is_holiday = ds in US_MARKET_HOLIDAYS
        if not is_weekend and not is_holiday:
            days_index[ds] = len(days_list)
            days_list.append(ds)
            last_trading = ds
        nearest_trading_day[ds] = last_trading
        curr += timedelta(days=1)

    # Second pass: for weekends/holidays, map to NEXT trading day
    next_td = days_list[-1]
    curr = end
    while curr >= start:
        ds = curr.strftime("%Y-%m-%d")
        if ds in days_index:
            next_td = ds
        else:
            nearest_trading_day[ds] = next_td
        curr -= timedelta(days=1)

    return days_list, days_index, nearest_trading_day


